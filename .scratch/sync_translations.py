def load(p):
    with open(p, "r", encoding="utf-8") as f:
        return json.load(f, object_pairs_hook=OrderedDict)

def save(p, d):
    with open(p, "w", encoding="utf-8") as f:
        json.dump(d, f, ensure_ascii=False, indent=2)
        f.write("\n")

en = load(EN_PATH)
en_keys = list(en.keys())
en_set = set(en_keys)

# Build per-language word dict: en token -> target token, derived from
# aligned pairs in the existing translation file.
def build_word_dict(lang):
    src = os.path.join(DIR, f"{lang}.json")
    d = load(src)
    out = {}
    for k, v in d.items():
        en_v = en.get(k)
        if not isinstance(en_v, str) or not isinstance(v, str):
            continue
        en_v = en_v.strip()
        v = v.strip()
        if not en_v or not v or en_v.lower() == v.lower():
            continue
        # Align tokens when counts match
        et = en_v.split()
        vt = v.split()
        if len(et) == len(vt):
            for a, b in zip(et, vt):
                if a.lower() == b.lower():
                    continue
                na = re.sub(r"[^a-zA-Z0-9'./-]", "", a)
                nb = re.sub(r"[^a-zA-Z0-9'./-]", "", b)
                if not na or not nb or na.isdigit() or nb.isdigit():
                    continue
                out.setdefault(na, nb)
                out.setdefault(na.lower(), nb)
    return out

WORD_DICTS = {lang: build_word_dict(lang) for lang in LANGS}

def protect_placeholders(s):
    phs = []
    def save(m):
        phs.append(m.group(0))
        return f"\x00{len(phs)-1}\x00"
    return re.sub(r"\{[^{}]*\}", save, s), phs

def restore_placeholders(s, phs):
    return re.sub(r"\x00(\d+)\x00", lambda m: phs[int(m.group(1))], s)

def translate_token(tok, lang):
    """Translate a single token using the word dict."""
    if not tok or not tok.isalpha():
        return tok
    wd = WORD_DICTS[lang]
    # Try exact then lower
    if tok in wd:
        return wd[tok]
    if tok.lower() in wd:
        return wd[tok.lower()]
    return tok

def translate(en_val, lang):
    if not isinstance(en_val, str):
        return en_val
    # 1) Try exact phrase
    phrase_map = PHRASE.get(lang, {})
    t = phrase_map.get(en_val) or phrase_map.get(en_val.lower())
    if t:
        return t
    # 2) Word-level
    s, phs = protect_placeholders(en_val)
    parts = re.split(r"(\s+)", s)
    out = []
    for p in parts:
        if p.strip() == "":
            out.append(p)
        else:
            # Strip punctuation, translate core, re-attach punctuation
            m = re.match(r"^([^a-zA-Z0-9]*)([a-zA-Z0-9'./-]+)(.*)$", p)
            if m:
                pre, core, post = m.groups()
                translated = translate_token(core, lang)
                out.append(pre + translated + post)
            else:
                out.append(p)
    return restore_placeholders("".join(out), phs)

stats = {}
for lang in LANGS:
    src = os.path.join(DIR, f"{lang}.json")
    d = load(src)
    # Drop outliers
    d = OrderedDict((k, v) for k, v in d.items() if k in en_set)
    out = OrderedDict()
    translated = 0
    kept = 0
    skipped = 0
    for k in en_keys:
        if k in d:
            out[k] = d[k]
            continue
        if k in SKIP_KEYS:
            out[k] = en[k]
            skipped += 1
            continue
        en_val = en[k]
        if not isinstance(en_val, str):
            out[k] = en_val
            skipped += 1
            continue
        tgt = translate(en_val, lang)
        out[k] = tgt
        if tgt != en_val:
            translated += 1
        else:
            kept += 1
    save(src, out)
    stats[lang] = (len(out), translated, kept, skipped)
    print(f"{lang}.json: {len(out)} keys | {translated} translated | {kept} keep-en | {skipped} skipped-placeholder")

